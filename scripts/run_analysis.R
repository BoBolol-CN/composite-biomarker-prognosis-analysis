if (.Platform$OS.type == "windows") invisible(Sys.setlocale("LC_CTYPE", ".UTF-8"))
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 1L) stop("Usage: Rscript scripts/run_analysis.R path/to/config.R", call. = FALSE)
self <- sub("^--file=", "", commandArgs()[grepl("^--file=", commandArgs())][1])
root <- dirname(dirname(normalizePath(self, winslash = "/")))
source(file.path(root, "scripts", "load.R")); bp_load(root)
env <- new.env(parent = globalenv()); sys.source(normalizePath(args[1], mustWork = TRUE), envir = env)
assert(exists("config", env, inherits = FALSE), "Configuration file must define config <- list(...).")
run_workflow(env$config)
